def _today() -> date:
    """Current date in IST. The server may run in UTC (Streamlit Cloud), where
    date.today() is a day behind IST between midnight and 5:30 AM."""
    return pd.Timestamp.now(tz="Asia/Kolkata").date()


def _display_names(emp: pd.DataFrame) -> pd.Series:
    """Short display name per employee, falling back to the full Jibble name."""
    if "display_name" in emp.columns:
        return emp["display_name"].fillna(emp["jibble_name"])
    return emp["jibble_name"]


def _flatten_employees(df: pd.DataFrame):
    emp = pd.json_normalize(df["employees"])
    df  = df.drop(columns=["employees"])
    df["Employee"] = _display_names(emp)
    df["Type"]     = emp["employment_type"].str.replace("_", " ").str.title()
    return df, emp


def _parse_date(val):
    """Parse a Supabase date value to a python date object, or None."""
    if val is None:
        return None
    try:
        if pd.isna(val):
            return None
    except (TypeError, ValueError):
        pass
    try:
        return date.fromisoformat(str(val)[:10])
    except (ValueError, TypeError):
        return None


def _filter_active_on(df: pd.DataFrame, snap_date_col: str = "snapshot_date") -> pd.DataFrame:
    """
    Drop rows where the snapshot_date is outside the employee's
    [joined_date, departed_date] active range.  Caller must have already
    flattened employees() and have _joined / _departed columns.
    """
    if df.empty or "_joined" not in df.columns:
        return df
    snap_dates = pd.to_datetime(df[snap_date_col]).dt.date
    join_ok    = df["_joined"].isna()    | (snap_dates >= df["_joined"])
    depart_ok  = df["_departed"].isna()  | (snap_dates <= df["_departed"])
    return df[join_ok & depart_ok].copy()


def _working_days_active(monday: date, friday: date, joined, departed) -> int:
    """Count Mon-Fri days in [monday, friday] within the employee's active range."""
    return sum(
        1 for i in range(5)
        if (joined is None or monday + timedelta(days=i) >= joined)
        and (departed is None or monday + timedelta(days=i) <= departed)
    )


def _fmt_hrs(h) -> str:
    try:
        h = float(h)
    except (TypeError, ValueError):
        return "—"
    if pd.isna(h):
        return "—"
    total_min = round(abs(h) * 60)
    return f"{total_min // 60}h {total_min % 60}m"


def _fmt_hrs_signed(h) -> str:
    """Signed variant of _fmt_hrs for net (±) values, e.g. '+3h 20m' / '−1h 05m'."""
    try:
        h = float(h)
    except (TypeError, ValueError):
        return "—"
    if pd.isna(h):
        return "—"
    sign = "−" if h < 0 else "+"
    total_min = round(abs(h) * 60)
    return f"{sign}{total_min // 60}h {total_min % 60}m"


def _parse_utc(val) -> "pd.Timestamp":
    """Parse a raw Supabase timestamptz value to a UTC-aware Timestamp, or NaT.

    Using the scalar pd.to_datetime path is intentional: the vectorised
    pd.to_datetime(series, utc=True) can silently coerce valid timezone-aware
    strings to NaT on some pandas builds when the column contains a mix of
    timezone-aware strings and None values.
    """
    if val is None:
        return pd.NaT
    try:
        if pd.isna(val):
            return pd.NaT
    except (TypeError, ValueError):
        pass
    return pd.to_datetime(val, utc=True, errors="coerce")


def _to_ist_str(val) -> str:
    """Convert a raw timestamptz value to an IST HH:MM AM/PM string, or '—'."""
    ts = _parse_utc(val)
    if pd.isna(ts):
        return "—"
    return ts.tz_convert("Asia/Kolkata").strftime("%I:%M %p")


def _fmt_map(df: pd.DataFrame, mapping: dict) -> dict:
    """Drop formatters for absent columns — optional ones like 'Weekend Hrs'
    only appear in ranges where somebody actually worked a weekend."""
    return {k: v for k, v in mapping.items() if k in df.columns}


def _style_weekend(styled, df: pd.DataFrame):
    """Tint the optional Weekend Hrs column when it is present."""
    if "Weekend Hrs" in df.columns:
        return styled.map(_color_weekend, subset=["Weekend Hrs"])
    return styled


