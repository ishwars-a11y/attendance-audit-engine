# PostgREST (Supabase) caps every response at 1000 rows by default.  Range
# queries that span more than ~2.5 months exceed that at current headcount, so a
# bare .execute() silently drops rows and under-counts everything (this is what
# made a Jan–Jun range show fewer leaves than April alone).  _fetch_all pages
# through the full result set so summaries are computed on complete data.
_PAGE_SIZE = 1000

def _fetch_all(build_query) -> list[dict]:
    """Return every row for a Supabase query, paging past the 1000-row API cap.

    `build_query` is a zero-arg callable returning a fresh query (select +
    filters + a stable .order()), WITHOUT range/limit applied.
    """
    rows: list[dict] = []
    offset = 0
    while True:
        batch = build_query().range(offset, offset + _PAGE_SIZE - 1).execute().data or []
        rows.extend(batch)
        if len(batch) < _PAGE_SIZE:
            return rows
        offset += _PAGE_SIZE


@st.cache_data(ttl=60)
def load_last_synced() -> str | None:
    """ISO timestamp of the most-recent engine run (global max pulled_at).
    Formatting and staleness are computed by the header so they always use the
    current clock rather than the cached value's age.
    """
    res = (
        sb.table("daily_snapshots")
        .select("pulled_at")
        .order("pulled_at", desc=True)
        .limit(1)
        .execute()
    )
    if not res.data:
        return None
    ts = _parse_utc(res.data[0].get("pulled_at"))
    return ts.isoformat() if pd.notna(ts) else None


@st.cache_data(ttl=60)
def load_daily_snapshot(snap_date: str) -> pd.DataFrame:
    """Returns formatted attendance DataFrame for snap_date."""
    rows = (
        sb.table("daily_snapshots")
        .select("snapshot_date, hours_logged, session_count, first_clock_in, last_clock_out, leave_type, pulled_at, "
                "employees(jibble_name, display_name, employment_type, daily_target_hrs, joined_date, departed_date)")
        .eq("snapshot_date", snap_date)
        .execute()
    )
    df = pd.DataFrame(rows.data)
    if df.empty:
        return df

    df, emp_raw = _flatten_employees(df)
    df["_daily_target"] = emp_raw["daily_target_hrs"].astype(float)
    df["_joined"]   = emp_raw["joined_date"].map(_parse_date)
    df["_departed"] = emp_raw["departed_date"].map(_parse_date)
    df = _filter_active_on(df)
    df = df.drop(columns=["_joined", "_departed"])
    if df.empty:
        return df

    # Parse timestamps element-by-element via the scalar path.
    # pd.to_datetime(series, utc=True) can silently coerce valid timezone-aware
    # strings to NaT when the column also contains None values on some pandas
    # versions, so we map the scalar helper across the column instead.
    first_ts = df["first_clock_in"].map(_parse_utc)   # object Series: Timestamps + NaT
    last_ts  = df["last_clock_out"].map(_parse_utc)

    # Break Hrs: span(clock-out − clock-in) minus worked hours
    def _span(fi, lo):
        if pd.isna(fi) or pd.isna(lo):
            return float("nan")
        return (lo - fi).total_seconds() / 3600

    span_hrs = pd.Series(
        [_span(fi, lo) for fi, lo in zip(first_ts, last_ts)], index=df.index
    )
    df["Break Hrs"] = (span_hrs - df["hours_logged"].astype(float)).clip(lower=0).round(2)

    df["first_clock_in"] = first_ts.map(_to_ist_str)
    df["last_clock_out"]  = last_ts.map(_to_ist_str)
    df["leave_type"]      = df["leave_type"].fillna("")

    df = df.rename(columns={
        "hours_logged":   "Total Hours",
        "session_count":  "Sessions",
        "first_clock_in": "Clock In",
        "last_clock_out": "Clock Out",
        "leave_type":     "Leave",
    })
    df = df.sort_values(["Total Hours", "Employee"]).drop(columns=["snapshot_date", "pulled_at"])
    # Leave moved to col 3 so it's always visible; _daily_target retained for
    # per-employee alert thresholds and dropped before display.
    return df[["Employee", "Type", "Leave", "Total Hours", "Break Hrs", "Sessions", "Clock In", "Clock Out", "_daily_target"]].reset_index(drop=True)


@st.cache_data(ttl=60)
def load_weekly_summary(week_start: str, week_end: str) -> pd.DataFrame:
    """
    Compute weekly summary LIVE from daily_snapshots — never reads the cached
    weekly_summaries table, so retroactive leave approvals are reflected the
    moment the engine re-syncs those days regardless of how old the week is.
    Targets are pro-rated by each employee's active range so joiners /
    departures within the week are handled correctly.
    """
    data = _fetch_all(lambda: (
        sb.table("daily_snapshots")
        .select("snapshot_date, hours_logged, leave_type, "
                "employees(jibble_name, display_name, employment_type, weekly_target_hrs, daily_target_hrs, joined_date, departed_date)")
        .gte("snapshot_date", week_start)
        .lte("snapshot_date", week_end)
        .order("id")
    ))
    df = pd.DataFrame(data)
    if df.empty:
        return df

    emp_cols = pd.json_normalize(df["employees"])
    df = df.drop(columns=["employees"])
    df["Employee"]       = _display_names(emp_cols)
    df["weekly_target"]  = emp_cols["weekly_target_hrs"].astype(float)
    df["daily_target"]   = emp_cols["daily_target_hrs"].astype(float)
    df["_joined"]        = emp_cols["joined_date"].map(_parse_date)
    df["_departed"]      = emp_cols["departed_date"].map(_parse_date)
    df["leave_type"]     = df["leave_type"].fillna("")
    df["hours_logged"]   = df["hours_logged"].astype(float)
    # Excused = personal leave OR public holiday (both reduce the target).
    # Leave  = personal leave only (holidays are not tallied as leave).
    df["_excused"]       = df["leave_type"] != ""
    df["_leave"]         = df["_excused"] & ~df["leave_type"].isin(HOLIDAY_LEAVE_TYPES)
    # Weekend catch-up hours count toward the week's total but never raise the
    # target — surfaced separately so it's clear where the hours came from.
    df["_weekend_hrs"]   = df["hours_logged"].where(
        pd.to_datetime(df["snapshot_date"]).dt.weekday >= 5, 0.0)

    # Drop snapshot rows outside each employee's active range
    df = _filter_active_on(df)
    if df.empty:
        return df

    monday = date.fromisoformat(week_start)
    friday = date.fromisoformat(week_end)

    agg = (
        df.groupby("Employee")
        .agg(
            Hours        = ("hours_logged", "sum"),
            Weekend_Hrs  = ("_weekend_hrs", "sum"),
            Excused_Days = ("_excused", "sum"),
            Leave_Days   = ("_leave",   "sum"),
            weekly_target= ("weekly_target", "first"),
            daily_target = ("daily_target",  "first"),
            _joined      = ("_joined",       "first"),
            _departed    = ("_departed",     "first"),
        )
        .reset_index()
    )

    # Pro-rated target: working days within active range × daily_target,
    # minus leave days within that window.
    agg["active_days"] = agg.apply(
        lambda r: _working_days_active(monday, friday, r["_joined"], r["_departed"]),
        axis=1,
    )
    agg = agg[agg["active_days"] > 0]   # drop employees with no overlap
    agg["Target"]  = ((agg["active_days"] - agg["Excused_Days"]) * agg["daily_target"]).clip(lower=0).round(2)
    agg["Deficit"] = (agg["Target"] - agg["Hours"]).clip(lower=0).round(2)

    def _status(row):
        if row["Hours"] >= row["Target"]:     return "Met"
        if row["Hours"] >= row["Target"] - 4: return "At Risk"
        return "Deficit"

    agg["Status"] = agg.apply(_status, axis=1)
    order = {"Deficit": 0, "At Risk": 1, "Met": 2}
    agg = agg.sort_values("Status", key=lambda s: s.map(order))
    agg = agg.rename(columns={"Leave_Days": "Leave Days", "Weekend_Hrs": "Weekend Hrs"})
    cols = ["Employee", "Status", "Hours", "Target", "Deficit", "Leave Days"]
    if agg["Weekend Hrs"].sum() > 0:   # only shown in weeks someone worked one
        cols.insert(4, "Weekend Hrs")
    return agg[cols].reset_index(drop=True)


@st.cache_data(ttl=60)
def load_current_week(monday: str, through: str) -> pd.DataFrame:
    if monday > through:
        return pd.DataFrame()

    data = _fetch_all(lambda: (
        sb.table("daily_snapshots")
        .select("snapshot_date, hours_logged, leave_type, "
                "employees(jibble_name, display_name, employment_type, weekly_target_hrs, daily_target_hrs, joined_date, departed_date)")
        .gte("snapshot_date", monday)
        .lte("snapshot_date", through)
        .order("id")
    ))
    df = pd.DataFrame(data)
    if df.empty:
        return df

    emp_cols = pd.json_normalize(df["employees"])
    df = df.drop(columns=["employees"])
    df["Employee"]      = _display_names(emp_cols)
    df["weekly_target"] = emp_cols["weekly_target_hrs"].astype(float)
    df["daily_target"]  = emp_cols["daily_target_hrs"].astype(float)
    df["_joined"]       = emp_cols["joined_date"].map(_parse_date)
    df["_departed"]     = emp_cols["departed_date"].map(_parse_date)
    df["leave_type"]    = df["leave_type"].fillna("")
    df["_excused"]      = df["leave_type"] != ""
    df["_leave"]        = df["_excused"] & ~df["leave_type"].isin(HOLIDAY_LEAVE_TYPES)

    df = _filter_active_on(df)
    if df.empty:
        return df

    monday_date = date.fromisoformat(monday)
    friday_date = monday_date + timedelta(days=4)
    today       = _today()

    # Split hours into completed days vs today: today's numbers are partial
    # (the engine syncs intra-day), so the projection must not treat today as a
    # finished day — that used to show most of the team in false "Deficit"
    # every morning.
    df["hours_logged"] = df["hours_logged"].astype(float)
    snap_dates         = pd.to_datetime(df["snapshot_date"]).dt.date
    # Only a *scheduled* day in progress is held back from the banked total and
    # extrapolated instead; weekend catch-up hours are voluntary and always
    # count in full, including on the day they're worked.
    _hold_back         = (snap_dates == today) & (today.weekday() < 5)
    df["_hours_pre"]   = df["hours_logged"].where(~_hold_back, 0.0)
    df["_leave_today"] = df["_excused"] & (snap_dates == today)
    df["_weekend_hrs"] = df["hours_logged"].where(
        pd.to_datetime(df["snapshot_date"]).dt.weekday >= 5, 0.0)

    agg = (
        df.groupby("Employee")
        .agg(
            Hours        = ("hours_logged", "sum"),
            Hours_Pre    = ("_hours_pre",   "sum"),
            Weekend_Hrs  = ("_weekend_hrs", "sum"),
            Excused_Days = ("_excused", "sum"),
            Leave_Days   = ("_leave",   "sum"),
            Leave_Today  = ("_leave_today", "max"),
            weekly_target= ("weekly_target", "first"),
            daily_target = ("daily_target",  "first"),
            _joined      = ("_joined",       "first"),
            _departed    = ("_departed",     "first"),
        )
        .reset_index()
    )

    # Pro-rated target uses active working days within Mon-Fri
    agg["active_days"] = agg.apply(
        lambda r: _working_days_active(monday_date, friday_date, r["_joined"], r["_departed"]),
        axis=1,
    )
    agg = agg[agg["active_days"] > 0]
    agg["Target"] = ((agg["active_days"] - agg["Excused_Days"]) * agg["daily_target"]).clip(lower=0)

    # Projected end-of-week = hours banked before today + (today and the
    # remaining working days at target pace, skipping a known leave day today).
    def _remaining_days(r):
        days = 0
        d = today
        while d <= friday_date:
            if d.weekday() < 5 \
               and (r["_joined"] is None or d >= r["_joined"]) \
               and (r["_departed"] is None or d <= r["_departed"]):
                days += 1
            d += timedelta(days=1)
        if r["Leave_Today"] and days > 0:
            days -= 1
        return days

    agg["Days Left"] = agg.apply(_remaining_days, axis=1)
    agg["Projected"] = (agg["Hours_Pre"] + agg["Days Left"] * agg["daily_target"]).round(2)

    def _status(row):
        if row["Projected"] >= row["Target"]:     return "On Track"
        if row["Projected"] >= row["Target"] - 4: return "At Risk"
        return "Deficit"

    agg["Status"] = agg.apply(_status, axis=1)
    order = {"Deficit": 0, "At Risk": 1, "On Track": 2}
    agg = agg.sort_values("Status", key=lambda s: s.map(order))
    agg = agg.rename(columns={"Leave_Days": "Leave Days", "Weekend_Hrs": "Weekend Hrs"})
    # Status first
    cols = ["Employee", "Status", "Hours", "Target", "Projected", "Leave Days", "Days Left"]
    if agg["Weekend Hrs"].sum() > 0:
        cols.insert(5, "Weekend Hrs")
    return agg[cols].reset_index(drop=True)


@st.cache_data(ttl=60)
def load_monthly_summary(start: str, end: str) -> pd.DataFrame:
    data = _fetch_all(lambda: (
        sb.table("daily_snapshots")
        .select("snapshot_date, hours_logged, leave_type, "
                "employees(jibble_name, display_name, employment_type, weekly_target_hrs, daily_target_hrs, joined_date, departed_date)")
        .gte("snapshot_date", start)
        .lte("snapshot_date", end)
        .order("id")
    ))
    df = pd.DataFrame(data)
    if df.empty:
        return df

    emp_cols = pd.json_normalize(df["employees"])
    df = df.drop(columns=["employees"])
    df["Employee"]     = _display_names(emp_cols)
    df["daily_target"] = emp_cols["daily_target_hrs"].astype(float)
    df["_joined"]      = emp_cols["joined_date"].map(_parse_date)
    df["_departed"]    = emp_cols["departed_date"].map(_parse_date)
    df["leave_type"]   = df["leave_type"].fillna("")
    df["hours_logged"] = df["hours_logged"].astype(float)
    # Excused = personal leave OR public holiday (both reduce expected hours).
    # Leave  = personal leave only (holidays are not tallied as leave).
    df["_excused"]     = df["leave_type"] != ""
    df["_leave"]       = df["_excused"] & ~df["leave_type"].isin(HOLIDAY_LEAVE_TYPES)
    df["_weekend_hrs"] = df["hours_logged"].where(
        pd.to_datetime(df["snapshot_date"]).dt.weekday >= 5, 0.0)

    # Drop snapshot rows outside each employee's active range
    df = _filter_active_on(df)
    if df.empty:
        return df

    # Compute Expected Hrs per-employee as (working_days in active range ∩ [start,end] − leave_days) × daily_target.
    start_d = date.fromisoformat(start)
    end_d   = date.fromisoformat(end)

    def _working_days_in_range(joined, departed) -> int:
        """Count Mon-Fri days in [start_d, end_d] within employee's active range."""
        lo = max(start_d, joined)   if joined   else start_d
        hi = min(end_d,   departed) if departed else end_d
        if hi < lo:
            return 0
        return sum(
            1 for i in range((hi - lo).days + 1)
            if (lo + timedelta(days=i)).weekday() < 5
        )

    agg = (
        df.groupby("Employee")
        .agg(
            Total_Hours  = ("hours_logged", "sum"),
            Weekend_Hrs  = ("_weekend_hrs", "sum"),
            Days_Present = ("hours_logged", lambda x: (x > 0).sum()),
            Days_Absent  = ("hours_logged", lambda x: ((x == 0) & (df.loc[x.index, "leave_type"] == "")).sum()),
            Excused_Days = ("_excused", "sum"),
            Leave_Days   = ("_leave",   "sum"),
            daily_target = ("daily_target", "first"),
            _joined      = ("_joined",       "first"),
            _departed    = ("_departed",     "first"),
        )
        .reset_index()
    )
    agg["working_days"] = agg.apply(
        lambda r: _working_days_in_range(r["_joined"], r["_departed"]), axis=1
    )
    agg = agg[agg["working_days"] > 0]
    agg["Expected Hrs"] = ((agg["working_days"] - agg["Excused_Days"]) * agg["daily_target"]).clip(lower=0).round(2)
    # Net (±) instead of deficit-only: surplus hours are informative too, and a
    # one-sided "Deficit" column hides people consistently over target.
    agg["Net Hrs"] = (agg["Total_Hours"] - agg["Expected Hrs"]).round(2)
    agg = agg.sort_values("Net Hrs")
    agg = agg.rename(columns={
        "Total_Hours": "Hours", "Days_Present": "Days Present",
        "Days_Absent": "Days Absent", "Leave_Days": "Leave Days",
        "Weekend_Hrs": "Weekend Hrs",
    })
    cols = ["Employee", "Net Hrs", "Hours", "Expected Hrs", "Days Present", "Days Absent", "Leave Days"]
    if agg["Weekend Hrs"].sum() > 0:
        cols.insert(4, "Weekend Hrs")
    return agg[cols].reset_index(drop=True)


@st.cache_data(ttl=60)
def load_anomalies(start: str, end: str) -> pd.DataFrame:
    data = _fetch_all(lambda: (
        sb.table("anomalies")
        .select("anomaly_date, anomaly_type, detail, employees(jibble_name, display_name, joined_date, departed_date)")
        .gte("anomaly_date", start)
        .lte("anomaly_date", end)
        .order("id")
    ))
    df = pd.DataFrame(data)
    if df.empty:
        return df

    emp = pd.json_normalize(df["employees"])
    df  = df.drop(columns=["employees"])
    df["Employee"]  = _display_names(emp)
    df["_joined"]   = emp["joined_date"].map(_parse_date)
    df["_departed"] = emp["departed_date"].map(_parse_date)
    df = df.rename(columns={"anomaly_date": "Date", "anomaly_type": "Type", "detail": "Detail"})

    # Hide deprecated anomaly types (Excessive Breaks, Early Departure) — they
    # are no longer generated but historical rows still exist.
    df = df[~df["Type"].isin(HIDDEN_ANOMALY_TYPES)]
    # Hide anomalies outside the employee's active range (e.g. stale Absence
    # flags for someone who'd already left or hadn't joined yet)
    df = _filter_active_on(df, snap_date_col="Date")
    df = df.drop(columns=["_joined", "_departed"])
    if df.empty:
        return df
    df["_sev"] = df["Type"].map(ANOMALY_SEVERITY).fillna(99)
    df = df.sort_values(["_sev", "Date"], ascending=[True, False]).drop(columns=["_sev"])
    return df[["Date", "Employee", "Type", "Detail"]].reset_index(drop=True)


@st.cache_data(ttl=60)
def load_anomaly_summary(start: str, end: str) -> pd.DataFrame:
    df = load_anomalies(start, end)
    if df.empty:
        return df

    type_cols = sorted(ANOMALY_SEVERITY, key=ANOMALY_SEVERITY.get)
    records = []
    for emp, grp in df.groupby("Employee"):
        row = {"Employee": emp, "Total": len(grp)}
        for t in type_cols:
            row[t] = int((grp["Type"] == t).sum())
        records.append(row)
    return pd.DataFrame(records).sort_values("Total", ascending=False).reset_index(drop=True)


